#!/usr/bin/env bash
# Build firmware/tab5_386/src/bios_rom.c from vendor/bios.bin and vendor/vgabios.bin (SeaBIOS, from tiny386's release).
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "// SeaBIOS and VGA BIOS images from tiny386's continuous release (LGPL-3, see vendor/tiny386/README.md);"
  echo "// generated by tools/gen_bios.sh, do not edit."
  echo '#include <stdint.h>'
  echo '#include <stddef.h>'
  for n in bios vgabios; do
    (cd vendor && xxd -i -n ${n}_rom $n.bin) |
      sed 's/^unsigned char/const uint8_t/; s/^unsigned int \(.*\) = \(.*\);/const size_t \1 = \2;/'
  done
} > firmware/tab5_386/src/bios_rom.c
echo "wrote firmware/tab5_386/src/bios_rom.c"
